#!/usr/bin/env python3
"""Generate trader-core/internal/strategies/gen_schema.go from shared/strategies.json.

The Go side embeds the schema (no runtime file needed) and registers every
primitive from it. The Python backtester (research/) reads the JSON directly
at runtime. Both engines execute the schema's test vectors in their test
suites, so behavior stays pinned on both sides.

Usage:
    python3 scripts/generate_strategies.py          # write gen_schema.go
    python3 scripts/generate_strategies.py --check  # exit 1 if stale (CI)
"""

import json
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = ROOT / "shared" / "strategies.json"
OUT_PATH = ROOT / "trader-core" / "internal" / "strategies" / "gen_schema.go"

# Templates implemented by hand in trader-core/internal/strategies and
# research/app/strategies. Adding a new template = implement it in both
# engines + allow it here; adding a new primitive on an existing template =
# edit shared/strategies.json only and re-run this script.
KNOWN_TEMPLATES = {
    "prev_close",
    "always_buy",
    "dca",
    "sma_cross",
    "http",
    "weighted_vote",
}

PARAM_TYPES = {
    "number": "ParamTypeNumber",
    "string": "ParamTypeString",
    "boolean": "ParamTypeBool",
    "select": "ParamTypeSelect",
}


def validate(schema: dict[str, Any]) -> None:
    if schema.get("version") != 1:
        raise ValueError("schema version must be 1")
    names = [p["name"] for p in schema["primitives"]]
    if len(names) != len(set(names)):
        raise ValueError(f"duplicate primitive names: {names}")
    for p in schema["primitives"]:
        if p["template"] not in KNOWN_TEMPLATES:
            raise ValueError(f"{p['name']}: unknown template {p['template']!r}")
        keys = [param["key"] for param in p.get("params", [])]
        if len(keys) != len(set(keys)):
            raise ValueError(f"{p['name']}: duplicate param keys {keys}")
        for param in p.get("params", []):
            if param["type"] not in PARAM_TYPES:
                raise ValueError(
                    f"{p['name']}.{param['key']}: bad type {param['type']!r}"
                )
        for case in p.get("test", {}).get("cases", []):
            if len(case["candles"]) != len(case["expect"]):
                raise ValueError(
                    f"{p['name']}: candles/expect length mismatch in {case}"
                )
        if p["template"] == "http":
            keys = [param["key"] for param in p.get("params", [])]
            if "url" not in keys:
                raise ValueError(f"{p['name']}: http template requires a 'url' param")
    if schema.get("composite", {}).get("template") not in KNOWN_TEMPLATES:
        raise ValueError("composite: unknown template")


def go_str(s: str) -> str:
    return json.dumps(s)  # valid Go string literal for our content


def go_param(param: dict[str, Any]) -> str:
    parts = [
        f"Key: {go_str(param['key'])}",
        f"Label: {go_str(param['label'])}",
        f"Type: {PARAM_TYPES[param['type']]}",
    ]
    if param.get("default") is not None:
        parts.append(f"Default: {go_literal(param['default'])}")
    if param.get("min") is not None:
        parts.append(f"Min: ptrFloat({go_literal(param['min'])})")
    if param.get("max") is not None:
        parts.append(f"Max: ptrFloat({go_literal(param['max'])})")
    if param.get("options"):
        opts = ", ".join(go_str(o) for o in param["options"])
        parts.append(f"Options: []string{{{opts}}}")
    return "{" + ", ".join(parts) + "}"


def go_literal(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return go_str(v)
    raise ValueError(f"unsupported literal {v!r}")


def gen_go(schema_text: str, schema: dict[str, Any]) -> str:
    if "`" in schema_text:
        raise ValueError("schema contains a backtick; cannot embed as Go raw string")

    lines = [
        "// Code generated by scripts/generate_strategies.py from shared/strategies.json. DO NOT EDIT.",
        "",
        "package strategies",
        "",
        "// generatedSchemaJSON is the embedded copy of shared/strategies.json.",
        "const generatedSchemaJSON = `" + schema_text + "`",
        "",
        "func init() {",
    ]
    for p in schema["primitives"]:
        params = p.get("params", [])
        if params:
            params_literal = (
                "[]ParamSchema{\n"
                + "".join(f"\t\t\t{go_param(param)},\n" for param in params)
                + "\t\t}"
            )
        else:
            params_literal = "[]ParamSchema{}"
        lines.append(
            f'\tRegister({go_str(p["name"])}, StrategySchema{{'
            f'Name: {go_str(p["name"])}, '
            f'DisplayName: {go_str(p["display_name"])}, '
            f"Params: {params_literal}, "
            f'}}, constructorFor({go_str(p["name"])}, {go_str(p["template"])}))'
        )
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def format_go(content: str) -> str:
    """gofmt the generated file when gofmt is available (CI + local Go setups)."""
    gofmt = shutil.which("gofmt")
    if not gofmt:
        return content
    proc = subprocess.run([gofmt], input=content, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(f"gofmt failed: {proc.stderr}")
    return proc.stdout


def main() -> int:
    schema_text = SCHEMA_PATH.read_text(encoding="utf-8")
    schema = json.loads(schema_text)
    validate(schema)
    content = format_go(gen_go(schema_text, schema))

    if "--check" in sys.argv:
        if OUT_PATH.exists() and OUT_PATH.read_text(encoding="utf-8") == content:
            print("gen_schema.go is up to date")
            return 0
        print(
            "ERROR: gen_schema.go is stale; run `python3 scripts/generate_strategies.py`"
        )
        return 1

    OUT_PATH.write_text(content, encoding="utf-8")
    print(f"wrote {OUT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
